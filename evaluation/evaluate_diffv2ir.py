#!/usr/bin/env python3
"""
评估DiffV2IR生成的红外图像质量
Evaluate the quality of infrared images generated by DiffV2IR
基于PID的评估脚本适配而来
Adapted from the PID evaluation script
处理：
Handles:
1. 分辨率不匹配：GT(640×512) vs 预测(512×448)
   Resolution mismatch: GT (640x512) vs prediction (512x448)
2. 通道不匹配：GT(灰度) vs 预测(RGB)
   Channel mismatch: GT (grayscale) vs prediction (RGB)
"""

import os
import numpy as np
from PIL import Image
import cv2
from skimage.metrics import peak_signal_noise_ratio as psnr
from skimage.metrics import structural_similarity as ssim
import argparse
from tqdm import tqdm
import json

def prepare_images_for_comparison(pred_path, gt_path, resize_method='resize'):
    """
    准备图像用于比较，处理分辨率和通道差异
    Prepare images for comparison, handling resolution and channel differences
    resize_method: 'resize' 或 'crop'
        resize_method: 'resize' or 'crop'
    """
    # 加载预测图像（RGB，512×448）
    # Load the prediction image (RGB, 512x448)
    pred_img = Image.open(pred_path)
    if pred_img.mode != 'RGB':
        pred_img = pred_img.convert('RGB')
    pred_array = np.array(pred_img)
    
    # 加载GT图像
    # Load the GT (ground-truth) image
    gt_img = Image.open(gt_path)

    # 处理分辨率差异
    # Handle the resolution difference
    if resize_method == 'resize':
        # 方法1：调整GT到预测图像尺寸
        # Method 1: resize GT to the prediction image size
        if gt_img.size != pred_img.size:
            gt_img = gt_img.resize(pred_img.size, Image.LANCZOS)
    elif resize_method == 'crop':
        # 方法2：从GT中心裁剪到预测图像尺寸
        # Method 2: center-crop GT to the prediction image size
        pred_w, pred_h = pred_img.size
        gt_w, gt_h = gt_img.size
        if gt_img.size != pred_img.size:
            # 计算中心裁剪区域
            # Compute the center-crop region
            left = max(0, (gt_w - pred_w) // 2)
            top = max(0, (gt_h - pred_h) // 2)
            right = min(gt_w, left + pred_w)
            bottom = min(gt_h, top + pred_h)
            gt_img = gt_img.crop((left, top, right, bottom))
            # 如果裁剪后尺寸还不匹配，进行resize
            # If the size still doesn't match after cropping, resize it
            if gt_img.size != pred_img.size:
                gt_img = gt_img.resize(pred_img.size, Image.LANCZOS)
    
    # 处理通道差异
    # Handle the channel difference
    if gt_img.mode == 'L':
        # GT是灰度图，将预测图像也转为灰度进行比较
        # GT is grayscale; convert the prediction to grayscale too for comparison
        pred_gray = pred_img.convert('L')
        pred_array = np.array(pred_gray)
        gt_array = np.array(gt_img)
    elif gt_img.mode == 'RGB':
        # 都是RGB
        # Both are RGB
        gt_array = np.array(gt_img)
        pred_array = np.array(pred_img)
    else:
        # 其他情况，都转为RGB
        # Any other case: convert both to RGB
        gt_img = gt_img.convert('RGB')
        gt_array = np.array(gt_img)
        if pred_img.mode != 'RGB':
            pred_img = pred_img.convert('RGB')
            pred_array = np.array(pred_img)
    
    return pred_array, gt_array, pred_img.size, Image.open(gt_path).size, gt_img.mode

def compute_metrics(pred_path, gt_path, resize_method='resize'):
    """计算单张图像的PSNR和SSIM
    Compute the PSNR and SSIM of a single image
    """
    pred_array, gt_array, pred_size, gt_original_size, gt_mode = \
        prepare_images_for_comparison(pred_path, gt_path, resize_method)

    # 确保数据类型正确
    # Ensure the data types are correct
    pred_array = pred_array.astype(np.uint8)
    gt_array = gt_array.astype(np.uint8)

    # 计算PSNR
    # Compute PSNR
    psnr_value = psnr(gt_array, pred_array, data_range=255)

    # 计算SSIM
    # Compute SSIM
    if len(gt_array.shape) == 2:
        # 灰度图像
        # Grayscale image
        ssim_value = ssim(gt_array, pred_array, data_range=255)
    else:
        # 彩色图像
        # Color image
        ssim_value = ssim(gt_array, pred_array, multichannel=True, channel_axis=2, data_range=255)
    
    return psnr_value, ssim_value, pred_size, gt_original_size, gt_mode


# ---------------------------------------------------------------------------
# Optional perceptual / distributional metrics: LPIPS (per-image) and FID (set-level).
# Both are opt-in. torch/torchvision/lpips are imported lazily so the PSNR/SSIM-only
# path keeps working without them.
# ---------------------------------------------------------------------------
_LPIPS_CACHE = {}
_INCEPTION_CACHE = None


def _get_lpips(net='alex'):
    """Lazily build (and cache) an LPIPS model. Returns None if lpips is unavailable."""
    if net in _LPIPS_CACHE:
        return _LPIPS_CACHE[net]
    try:
        import torch
        import lpips
    except Exception as e:  # noqa: BLE001
        print(f"[warn] LPIPS unavailable ({e}); skipping LPIPS. Install with: pip install lpips")
        return None
    device = 'cuda' if torch.cuda.is_available() else 'cpu'
    fn = lpips.LPIPS(net=net).to(device).eval()
    _LPIPS_CACHE[net] = fn
    print(f"LPIPS loaded (net={net}, device={device})")
    return fn


def _rgb01(array):
    """Convert an aligned uint8 array (H,W) or (H,W,3) to a float [0,1] (3,H,W) array."""
    arr = np.asarray(array)
    if arr.ndim == 2:
        arr = np.stack([arr] * 3, axis=-1)
    return arr.astype(np.float32).transpose(2, 0, 1) / 255.0


def compute_lpips(pred_array, gt_array, net='alex'):
    """Per-image LPIPS (lower is better) for two aligned uint8 arrays of the same size."""
    fn = _get_lpips(net)
    if fn is None:
        return None
    import torch
    p = torch.from_numpy(_rgb01(pred_array)).unsqueeze(0) * 2.0 - 1.0  # -> [-1,1] (1,3,H,W)
    g = torch.from_numpy(_rgb01(gt_array)).unsqueeze(0) * 2.0 - 1.0
    device = next(fn.parameters()).device
    with torch.no_grad():
        val = fn(p.to(device), g.to(device))
    return float(val.item())


def _get_inception(device=None):
    """Lazily build (and cache) a feature-only InceptionV3 (2048-d pool output)."""
    global _INCEPTION_CACHE
    if _INCEPTION_CACHE is not None:
        return _INCEPTION_CACHE
    import torch
    import torch.nn as nn
    from torchvision.models import inception_v3
    if device is None:
        device = 'cuda' if torch.cuda.is_available() else 'cpu'
    model = inception_v3(pretrained=True, transform_input=False)
    model.fc = nn.Identity()  # keep the 2048-d pool features instead of the class logits
    model.eval().to(device)
    _INCEPTION_CACHE = (model, device)
    print(f"InceptionV3 loaded for FID (device={device})")
    return _INCEPTION_CACHE


def inception_features(paths, target=(299, 299), batch=16, device=None):
    """Inception 2048-d features for a list of image paths. Returns an (N, 2048) float32 array."""
    model, device = _get_inception(device)
    import torch
    feats = []
    for i in range(0, len(paths), batch):
        chunk = paths[i:i + batch]
        imgs = [np.asarray(Image.open(p).convert('RGB').resize(target, Image.BILINEAR), dtype=np.uint8)
                for p in chunk]
        t = torch.from_numpy(np.stack(imgs)).permute(0, 3, 1, 2).float() / 255.0  # (B,3,H,W) [0,1]
        with torch.no_grad():
            f = model(t.to(device))
        feats.append(f.float().cpu().numpy())
    if not feats:
        return np.zeros((0, 0), dtype=np.float32)
    return np.concatenate(feats, axis=0).astype(np.float32)


def frechet_distance(feats_a, feats_b, eps=1e-5):
    """Frechet distance between two (N, D) feature arrays (the FID core). None if <2 samples."""
    if feats_a is None or feats_b is None:
        return None
    feats_a = np.asarray(feats_a, dtype=np.float64)
    feats_b = np.asarray(feats_b, dtype=np.float64)
    if feats_a.size == 0 or feats_b.size == 0:
        return None
    if feats_a.shape[0] < 2 or feats_b.shape[0] < 2:
        return None
    mu_a = feats_a.mean(axis=0)
    mu_b = feats_b.mean(axis=0)
    cov_a = np.cov(feats_a, rowvar=False)
    cov_b = np.cov(feats_b, rowvar=False)
    diff = mu_a - mu_b
    mean_term = float(diff @ diff)
    prod = cov_a @ cov_b
    # trace(sqrtm(prod)): eigenvalues of the symmetrized product are real and >= 0.
    evals = np.linalg.eigvalsh((prod + prod.T) / 2.0)
    evals = np.clip(evals, 0.0, None)
    sqrtm_trace = float(np.sqrt(evals).sum())
    fid = mean_term + float(np.trace(cov_a)) + float(np.trace(cov_b)) - 2.0 * sqrtm_trace
    return float(fid)


def compute_fid(pred_paths, gt_paths, device=None):
    """Set-level FID (lower is better) between two lists of image paths. None if <2 samples."""
    if len(pred_paths) < 2 or len(gt_paths) < 2:
        print("[warn] FID needs at least 2 matched images; skipping")
        return None
    pred_feats = inception_features(pred_paths, device=device)
    gt_feats = inception_features(gt_paths, device=device)
    return frechet_distance(pred_feats, gt_feats)


def evaluate_dataset(pred_dir, gt_dir, output_file=None, resize_method='resize',
                     lpips_net=None, compute_fid_flag=False):
    """评估整个数据集
    Evaluate the entire dataset
    """
    results = {}
    psnr_list = []
    ssim_list = []
    lpips_list = []
    matched_pred_paths = []
    matched_gt_paths = []
    size_info = {}
    mode_info = {}

    # 获取所有预测图像文件
    # Get all prediction image files
    pred_files = sorted([f for f in os.listdir(pred_dir) if f.lower().endswith(('.png', '.jpg'))])

    # original text:"找到 {len(pred_files)} 张预测图像"
    print(f"Found {len(pred_files)} prediction images")
    # original text:"处理方法: {resize_method}"
    print(f"Processing method: {resize_method}")
    # original text:"注意："
    print("Note:")
    # original text:"  - GT灰度图像将与预测图像的灰度版本进行比较"
    print("  - Grayscale GT images will be compared against the grayscale version of the predictions")
    if resize_method == 'resize':
        # original text:"  - GT图像将被调整到预测图像的分辨率"
        print("  - GT images will be resized to the prediction resolution")
    else:
        # original text:"  - GT图像将被中心裁剪到预测图像的分辨率"
        print("  - GT images will be center-cropped to the prediction resolution")

    # 处理每张图像
    # Process each image
    # original text:"评估中"
    for filename in tqdm(pred_files, desc="Evaluating"):
        pred_path = os.path.join(pred_dir, filename)
        gt_path = os.path.join(gt_dir, filename)
        
        # 检查GT图像是否存在
        # Check whether the GT image exists
        if not os.path.exists(gt_path):
            # original text:"警告: 未找到对应的GT图像 {filename}"
            print(f"Warning: no corresponding GT image found for {filename}")
            continue

        # 计算指标
        # Compute the metrics
        try:
            psnr_val, ssim_val, pred_size, gt_original_size, gt_mode = \
                compute_metrics(pred_path, gt_path, resize_method)

            # LPIPS (opt-in): reuse the same alignment as PSNR/SSIM
            lpips_val = None
            if lpips_net is not None:
                lp_pred, lp_gt, _, _, _ = prepare_images_for_comparison(pred_path, gt_path, resize_method)
                lpips_val = compute_lpips(lp_pred, lp_gt, net=lpips_net)

            # 保存结果
            # Save the result
            results[filename] = {
                'psnr': float(psnr_val),
                'ssim': float(ssim_val),
                'pred_size': pred_size,
                'gt_original_size': gt_original_size,
                'gt_mode': gt_mode
            }
            if lpips_val is not None:
                results[filename]['lpips'] = float(lpips_val)
                lpips_list.append(lpips_val)

            psnr_list.append(psnr_val)
            ssim_list.append(ssim_val)
            matched_pred_paths.append(pred_path)
            matched_gt_paths.append(gt_path)

            # 记录尺寸信息
            # Record size information
            size_key = f"{pred_size} <- {gt_original_size}"
            if size_key not in size_info:
                size_info[size_key] = 0
            size_info[size_key] += 1

            # 记录模式信息
            # Record mode (color format) information
            if gt_mode not in mode_info:
                mode_info[gt_mode] = 0
            mode_info[gt_mode] += 1

        except Exception as e:
            # original text:"处理 {filename} 时出错: {e}"
            print(f"Error while processing {filename}: {e}")
            continue
    
    # 计算平均值
    # Compute the averages
    avg_psnr = np.mean(psnr_list) if psnr_list else 0
    avg_ssim = np.mean(ssim_list) if ssim_list else 0
    std_psnr = np.std(psnr_list) if psnr_list else 0
    std_ssim = np.std(ssim_list) if ssim_list else 0
    avg_lpips = float(np.mean(lpips_list)) if lpips_list else None
    std_lpips = float(np.std(lpips_list)) if lpips_list else None

    # FID (opt-in, set-level): compare all matched predictions against all GT images
    fid_value = None
    if compute_fid_flag:
        fid_value = compute_fid(matched_pred_paths, matched_gt_paths)

    # 汇总结果
    # Summarize the results
    summary = {
        'total_images': len(psnr_list),
        'average_psnr': float(avg_psnr),
        'std_psnr': float(std_psnr),
        'average_ssim': float(avg_ssim),
        'std_ssim': float(std_ssim),
        'min_psnr': float(np.min(psnr_list)) if psnr_list else 0,
        'max_psnr': float(np.max(psnr_list)) if psnr_list else 0,
        'min_ssim': float(np.min(ssim_list)) if ssim_list else 0,
        'max_ssim': float(np.max(ssim_list)) if ssim_list else 0,
        'resize_method': resize_method,
        'size_conversions': size_info,
        'gt_modes': mode_info,
        'per_image_results': results
    }
    if lpips_net is not None:
        summary['lpips_net'] = lpips_net
        summary['average_lpips'] = avg_lpips
        summary['std_lpips'] = std_lpips
        summary['min_lpips'] = float(np.min(lpips_list)) if lpips_list else None
        summary['max_lpips'] = float(np.max(lpips_list)) if lpips_list else None
    if compute_fid_flag:
        summary['fid'] = fid_value
    
    # 打印结果
    # Print the results
    print("\n" + "="*60)
    # original text:"DiffV2IR评估结果汇总（{resize_method}方法）"
    print(f"DiffV2IR evaluation summary ({resize_method} method)")
    print("="*60)
    # original text:"评估图像数量: {summary['total_images']}"
    print(f"Number of evaluated images: {summary['total_images']}")
    # original text:"平均 PSNR: {summary['average_psnr']:.2f} ± {summary['std_psnr']:.2f} dB"
    print(f"Average PSNR: {summary['average_psnr']:.2f} +/- {summary['std_psnr']:.2f} dB")
    # original text:"PSNR 范围: [{summary['min_psnr']:.2f}, {summary['max_psnr']:.2f}]"
    print(f"PSNR range: [{summary['min_psnr']:.2f}, {summary['max_psnr']:.2f}]")
    # original text:"平均 SSIM: {summary['average_ssim']:.4f} ± {summary['std_ssim']:.4f}"
    print(f"Average SSIM: {summary['average_ssim']:.4f} +/- {summary['std_ssim']:.4f}")
    # original text:"SSIM 范围: [{summary['min_ssim']:.4f}, {summary['max_ssim']:.4f}]"
    print(f"SSIM range: [{summary['min_ssim']:.4f}, {summary['max_ssim']:.4f}]")
    if lpips_net is not None and avg_lpips is not None:
        print(f"Average LPIPS ({lpips_net}): {avg_lpips:.4f} +/- {std_lpips:.4f}  (lower is better)")
        print(f"LPIPS range: [{summary['min_lpips']:.4f}, {summary['max_lpips']:.4f}]")
    if compute_fid_flag:
        if fid_value is not None:
            print(f"FID: {fid_value:.2f}  (lower is better)")
        else:
            print("FID: n/a (need at least 2 matched images)")
    # original text:"\n图像信息:"
    print("\nImage information:")
    # original text:"  分辨率转换:"
    print("  Resolution conversions:")
    for size_conv, count in size_info.items():
        # original text:"    {size_conv}: {count} 张"
        print(f"    {size_conv}: {count}")
    # original text:"  GT图像模式:"
    print("  GT image modes:")
    for mode, count in mode_info.items():
        # original text:"    {mode}: {count} 张"
        print(f"    {mode}: {count}")
    print("="*60)
    
    # 保存结果到文件
    # Save the results to a file
    if output_file:
        output_dir = os.path.dirname(output_file)
        # 只有当目录不为空时才创建
        # Only create the directory when it is non-empty
        if output_dir:
            os.makedirs(output_dir, exist_ok=True)
        with open(output_file, 'w') as f:
            json.dump(summary, f, indent=2, ensure_ascii=False)
        # original text:"\n详细结果已保存到: {output_file}"
        print(f"\nDetailed results saved to: {output_file}")
    
    return summary

def compare_methods(pred_dir, gt_dir, lpips_net=None, compute_fid_flag=False):
    """比较不同处理方法的结果
    Compare the results of the different processing methods
    """
    # 使用resize方法
    # Use the resize method
    # original text:"\n>>> 方法1: Resize (调整GT尺寸)"
    print("\n>>> Method 1: Resize (resize GT size)")
    results_resize = evaluate_dataset(
        pred_dir, 
        gt_dir,
        'diffv2ir_evaluation_resize.json',
        'resize',
        lpips_net=lpips_net,
        compute_fid_flag=compute_fid_flag
    )

    # 使用crop方法
    # Use the crop method
    # original text:"\n>>> 方法2: Crop (中心裁剪GT)"
    print("\n>>> Method 2: Crop (center-crop GT)")
    results_crop = evaluate_dataset(
        pred_dir,
        gt_dir, 
        'diffv2ir_evaluation_crop.json',
        'crop',
        lpips_net=lpips_net,
        compute_fid_flag=compute_fid_flag
    )

    # 对比结果
    # Compare the results
    print("\n" + "="*60)
    # original text:"DiffV2IR方法对比"
    print("DiffV2IR method comparison")
    print("="*60)
    # original text:"{'方法':<10} {'PSNR':<15} {'SSIM':<15}"
    print(f"{'Method':<10} {'PSNR':<15} {'SSIM':<15}")
    print("-"*40)
    print(f"{'Resize':<10} {results_resize['average_psnr']:<15.2f} {results_resize['average_ssim']:<15.4f}")
    print(f"{'Crop':<10} {results_crop['average_psnr']:<15.2f} {results_crop['average_ssim']:<15.4f}")
    print("="*60)
    
    return results_resize, results_crop

if __name__ == "__main__":
    # original text:"评估DiffV2IR红外图像生成质量"
    parser = argparse.ArgumentParser(description='Evaluate the quality of DiffV2IR infrared image generation')
    # original text:"预测图像目录"
    parser.add_argument('--pred_dir', type=str, 
                        default='data_for_diffv2ir/output',
                        help='Prediction image directory')
    # original text:"真实图像目录"
    parser.add_argument('--gt_dir', type=str,
                        default='data_for_diffv2ir/ground_truth',
                        help='Ground-truth image directory')
    # original text:"输出结果文件"
    parser.add_argument('--output', type=str,
                        default='diffv2ir_evaluation.json',
                        help='Output results file')
    # original text:"处理方法: resize(调整尺寸), crop(中心裁剪), both(比较两种)"
    parser.add_argument('--method', type=str, default='resize',
                        choices=['resize', 'crop', 'both'],
                        help='Processing method: resize (adjust size), crop (center-crop), both (compare the two)')
    parser.add_argument('--lpips-net', type=str, default=None,
                        choices=['alex', 'vgg', 'squeeze'],
                        help='Enable LPIPS with the given backbone (lower is better). Off by default.')
    parser.add_argument('--fid', action='store_true',
                        help='Compute set-level FID (lower is better) over all matched pred/GT images.')

    args = parser.parse_args()

    if args.method == 'both':
        compare_methods(args.pred_dir, args.gt_dir, lpips_net=args.lpips_net, compute_fid_flag=args.fid)
    else:
        evaluate_dataset(args.pred_dir, args.gt_dir, args.output, args.method,
                         lpips_net=args.lpips_net, compute_fid_flag=args.fid)